// Read-only image measurements produce static runtime metadata. Only committed,
// complete and transparent atlas pairs can enter the registry; PNGs stay intact.
import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {pngAlpha} from '../tests/pngAlpha.mjs';
const root=fileURLToPath(new URL('..',import.meta.url));
const tracked=new Set(execFileSync('git',['ls-tree','-r','--name-only','HEAD','assets/actors/bosses'],{cwd:root,encoding:'utf8'}).trim().split('\n'));
const median=values=>{const a=values.sort((a,b)=>a-b),i=Math.floor(a.length/2);return a.length%2?a[i]:(a[i-1]+a[i])/2;};
const targets={'forest-mini-0':110,'forest-mini-1':96,'forest-mini-2':96,'forest-mini-3':104,'forest-world-4':160,'forest-world-5':152,'north-world-5':145,'ancient-world-4':185,'ancient-world-5':175};
const result={};
for(const path of [...tracked].filter(p=>p.endsWith('.png')).sort()){
 const json=path.replace(/\.png$/,'.json');if(!tracked.has(json))continue;
 const id=path.split('/').at(-1).slice(0,-4),atlas=JSON.parse(readFileSync(join(root,json),'utf8')),{width,height,alpha}=pngAlpha(join(root,path));
 if(width!==1536||height!==1024||alpha[0]>2||alpha[width-1]>2)throw Error('Invalid size or background: '+id);
 let clear=0;for(const a of alpha)if(a<=2)clear++;if(clear<width*height*.2)throw Error('Background remains: '+id);
 for(let x=192;x<width;x+=192)for(let y=0;y<height;y++)if(alpha[y*width+x]>127)throw Error('Vertical bleed: '+id);
 for(let y=256;y<height;y+=256)for(let x=0;x<width;x++)if(alpha[y*width+x]>127)throw Error('Horizontal bleed: '+id);
 const feet={},heights={};
 for(const [row,bank]of ['idle','run-a','run-b','attack'].entries()){
  const bottoms=[],sizes=[];
  for(const [column,direction]of ['e','se','s','sw','w','nw','n','ne'].entries()){
   const frame=atlas.frames[bank+'/'+direction]?.frame;if(!frame||frame.x!==column*192||frame.y!==row*256||frame.w!==192||frame.h!==256)throw Error('Missing or misplaced pose: '+id+'/'+bank+'/'+direction);
   let top=256,bottom=-1;for(let y=0;y<256;y++)for(let x=0;x<192;x++)if(alpha[(row*256+y)*width+column*192+x]>=100){top=Math.min(top,y);bottom=Math.max(bottom,y);}
   if(bottom<top)throw Error('Empty pose: '+id+'/'+bank+'/'+direction);bottoms.push(bottom+1);sizes.push(bottom-top+1);
  }
  feet[bank]=median(bottoms);heights[bank]=median(sizes);
 }
 const world=id.includes('-world-'),target=targets[id]||(world?160:id.startsWith('dungeon')?110:105),scale=Math.round(target/heights.idle/(world?1.9:1.45)*1000)/1000;
 result[id]={key:'actor-boss-'+id,url:path,atlasURL:json,scale,annotationHeight:Math.round((heights.idle*scale+8)*100)/100,baselines:feet};
}
writeFileSync(join(root,'js/assets/bossArt.js'),'// Generated by scripts/register-boss-art.mjs from committed, pixel-verified atlas pairs.\nexport const BOSS_ART=Object.freeze('+JSON.stringify(result,null,1)+');\n');
console.log(JSON.stringify({registeredBossAtlases:Object.keys(result).length,ids:Object.keys(result)}));
